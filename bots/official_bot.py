"""NEXTGEN AI — OFFICIAL bot (long polling).

Requires a one-time linking code generated by an authenticated user in the web
platform. Serves only the organization that code belongs to.
"""
from __future__ import annotations

import asyncio
import logging

from aiogram import Bot, Dispatcher
from aiogram.client.default import DefaultBotProperties
from aiogram.enums import ParseMode

from bots.common.api import BackendClient
from bots.common.config import load_config
from bots.common.handlers import SessionCache, build_router

log = logging.getLogger("nextgen.bot.official")


async def run() -> None:
    cfg = load_config("official")
    api = BackendClient(cfg)
    bot = Bot(token=cfg.token, default=DefaultBotProperties(parse_mode=ParseMode.HTML))
    dp = Dispatcher()
    dp.include_router(build_router(cfg, api, SessionCache()))
    log.info("OFFICIAL bot starting (linked production accounts only)")
    try:
        await dp.start_polling(bot, allowed_updates=["message", "callback_query"])
    finally:
        await api.close()
        await bot.session.close()


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO)
    asyncio.run(run())
